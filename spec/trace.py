#!/usr/bin/env python3
"""REQ: T10.6 — the requirement check: every P0 requirement in `spec/01` against its tests and
other evidence, found by the traceability rules in AGENTS.md:

- Rust tests named after the requirement (`fn dns_001_...`), anywhere under `crates/` and `fuzz/`;
- Playwright tests whose title starts with it (`test('obs_028 node compare'`), in `ui/tests/`;
- end-to-end scripts and CI steps that say `REQ: DNS-001` (`deploy/`, `bench/`, `.github/`);
- fuzz targets, documents, and other evidence listed by hand in `spec/trace-evidence.toml`
  (for requirements a test can't show, such as "the image is built FROM scratch").

Writes `docs/v1-requirements.md`. `--check` fails if it's stale or a P0 has no evidence at all.
Usage: python3 spec/trace.py [--check]
"""
import re
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "v1-requirements.md"
EVIDENCE = ROOT / "spec" / "trace-evidence.toml"


def requirements() -> list[tuple[str, str]]:
    rows = []
    for line in (ROOT / "spec" / "01-requirements.md").read_text().splitlines():
        m = re.match(r"^\| ([A-Z]+-\d{3}) \| P0 \| (.*) \|$", line)
        if m:
            text = re.sub(r"\*\*|`", "", m.group(2))
            rows.append((m.group(1), text))
    return rows


def files(globs: list[str]) -> list[Path]:
    out = []
    for g in globs:
        out.extend(p for p in ROOT.glob(g) if p.is_file() and "/target/" not in str(p) and "node_modules" not in str(p))
    return sorted(set(out))


def rust_tests() -> dict[str, list[str]]:
    by: dict[str, list[str]] = {}
    for p in files(["crates/**/*.rs", "fuzz/**/*.rs"]):
        text = p.read_text(errors="replace")
        for m in re.finditer(r"#\[(?:tokio::)?test[^\]]*\]\s*(?:#\[[^\]]*\]\s*)*(?:async\s+)?fn\s+([a-z]+_\d{3})_(\w+)", text):
            by.setdefault(m.group(1).upper().replace("_", "-"), []).append(f"{m.group(1)}_{m.group(2)}")
    return by


def ui_tests() -> dict[str, list[str]]:
    by: dict[str, list[str]] = {}
    for p in files(["ui/tests/**/*.ts"]):
        for m in re.finditer(r"test\(\s*['\"]([a-z]+_\d{3})\s+([^'\"]+)['\"]", p.read_text(errors="replace")):
            by.setdefault(m.group(1).upper().replace("_", "-"), []).append(f"{m.group(1)} {m.group(2)}")
    return by


def scripted() -> dict[str, list[str]]:
    by: dict[str, list[str]] = {}
    for p in files(["deploy/**/*.sh", "deploy/**/*.py", "bench/**/*.sh", "bench/**/*.py", ".github/workflows/*.yml", "fuzz/fuzz_targets/*.rs"]):
        text = p.read_text(errors="replace")
        for m in re.finditer(r"REQ:\s*((?:[A-Z]+-\d{3}(?:\s*,\s*)?)+)", text):
            for rid in re.findall(r"[A-Z]+-\d{3}", m.group(1)):
                rel = str(p.relative_to(ROOT))
                lst = by.setdefault(rid, [])
                if rel not in lst:
                    lst.append(rel)
    return by


def code_refs() -> dict[str, int]:
    n: dict[str, int] = {}
    for p in files(["crates/**/*.rs", "ui/src/**/*.ts", "ui/src/**/*.svelte"]):
        for rid in re.findall(r"REQ:[^\n]*?([A-Z]+-\d{3})", p.read_text(errors="replace")):
            n[rid] = n.get(rid, 0) + 1
    return n


def manual() -> dict[str, list[str]]:
    if not EVIDENCE.exists():
        return {}
    data = tomllib.loads(EVIDENCE.read_text())
    return {k: list(v) for k, v in data.get("evidence", {}).items()}


def render() -> tuple[str, list[str]]:
    reqs = requirements()
    rt, ut, sc, cr, mn = rust_tests(), ui_tests(), scripted(), code_refs(), manual()
    lines = [
        "# v1.0 requirement check",
        "",
        "Every P0 requirement in `spec/01` against its tests and other evidence (T10.6). Generated by",
        "`python3 spec/trace.py` from the traceability rules in `AGENTS.md`: Rust tests named after the",
        "requirement, Playwright tests titled with it, end-to-end scripts and CI steps marked `REQ:`, and",
        "the evidence listed in `spec/trace-evidence.toml` for what a test can't show. CI runs every one",
        "of these on each push to `main`.",
        "",
        "| Requirement | Tests | End-to-end and CI | Other evidence | Code |",
        "|---|---|---|---|---|",
    ]
    bare = []
    tested = 0
    for rid, text in reqs:
        t = rt.get(rid, []) + ut.get(rid, [])
        s = sc.get(rid, [])
        m = mn.get(rid, [])
        if t:
            tested += 1
        if not (t or s or m):
            bare.append(rid)
        short = text if len(text) <= 90 else text[:87].rstrip() + "…"
        tests = f"{len(t)}: " + ", ".join(f"`{x}`" for x in t[:3]) + (" …" if len(t) > 3 else "") if t else "—"
        lines.append(
            f"| **{rid}** {short} | {tests} | {', '.join(f'`{x}`' for x in s) or '—'} | {'; '.join(m) or '—'} | {cr.get(rid, 0)} |"
        )
    lines += [
        "",
        f"**{len(reqs)} P0 requirements:** {tested} with tests, {len(reqs) - len(bare)} with some evidence, "
        f"{len(bare)} with none{(': ' + ', '.join(bare)) if bare else ''}.",
        "",
    ]
    return "\n".join(lines), bare


def main() -> None:
    text, bare = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            sys.exit(f"{OUT} is stale: run python3 spec/trace.py")
        if bare:
            sys.exit(f"P0 requirements without evidence: {', '.join(bare)}")
        print(f"{OUT.name} OK")
        return
    OUT.write_text(text)
    print(text.splitlines()[-2] if text.endswith("\n") else text.splitlines()[-1])


if __name__ == "__main__":
    main()
